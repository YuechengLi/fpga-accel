#!/usr/bin/env python3
"""Stage 5 compiler: fusion pass.

Rewrites the captured IR graph into the form the hardware executes:

  * pad -> conv2d          : fold the pad into the conv (pad + pad_mode).
                             aten.conv2d's own symmetric padding becomes
                             pad=(ph,ph,pw,pw), pad_mode='zero'.
  * conv2d -> relu         : fuse into the conv output stage
                             (fused_act='relu'; in the fixed-point domain
                             the [0,255] saturation already clips
                             negatives, so the fusion is free).
  * conv2d -> leaky_relu   : fuse (fused_act='leaky', slope).
  * conv2d -> batch_norm   : fold BN into the conv weights/bias
                             (W' = W*g/sqrt(var+eps),
                              b' = (b-mean)*g/sqrt(var+eps)+beta).
                             DnCNN's released weights have NO BN, so this
                             is exercised by unit test only.
  * conv2d -> sigmoid/tanh/gelu/silu : rewrite the act node to op
                             "act" (a SEPARATE LUT module, mode mlut or
                             pwl; the table is generated by passes/mlut.py
                             and passes/actapprox.py). NOT fused.
  * add/sub (two tensors)  : "residual" (elementwise, residual.sv).
  * mul (two tensors)      : "simplegate" (elementwise multiply).
  * conv2d -> pool         : pool fusion -- the pool consumes the conv
                             output on-chip (same fusion group, no DRAM
                             round-trip). The pool stays a separate node
                             (separate module).

Fusion groups: consecutive ops that can stay on-chip form a group.
A group is cut at a residual/simplegate (needs two streams), an
upsample / concat / layer_norm (resolution change or a full-frame
module), or when the group's tile intermediate would exceed the tile
buffer budget (64x64x64ch = 256 KB, plan §2). Ops inside one group
never touch DRAM for intermediates; the DRAM model (sw/common/dram.py)
counts zero intermediate traffic inside a group.
"""
import copy
import numpy as np

COMPLEX_ACTS = ("sigmoid", "tanh", "gelu", "silu")
TILE_BUFFER_BUDGET = 64 * 64 * 64  # bytes, plan §2 (64x64 tile, 64ch, 1B/px)


def _normalize_pad(kwargs):
    """Convert the capture's symmetric pad (ph, pw) to golden
    (t, b, l, r) and record pad_mode (default 'zero')."""
    pad = kwargs.get("pad", (0, 0))
    if isinstance(pad, (list, tuple)) and len(pad) == 2:
        ph, pw = int(pad[0]), int(pad[1])
        kwargs["pad"] = (ph, ph, pw, pw)
    kwargs.setdefault("pad_mode", "zero")
    return kwargs


def fuse(graph, tile_buffer_budget=TILE_BUFFER_BUDGET):
    """Run the fusion pass. Returns (new_graph, groups, report).

    ``groups`` is a list of lists of node names (one group = one
    on-chip fusion group). ``report`` is a list of human-readable
    strings describing each fusion decision.
    """
    from ir import Graph, Node
    report = []
    # Work on a deep copy so the input graph is untouched.
    nodes = [copy.deepcopy(n) for n in graph.nodes]
    by_name = {n.name: n for n in nodes}

    # ---- pass 1: normalize conv pads -------------------------------
    for n in nodes:
        if n.op in ("conv2d", "dw_conv2d", "linear"):
            _normalize_pad(n.kwargs)

    # ---- pass 2: fold pad -> conv, BN -> conv -----------------------
    # (single forward sweep; a node consumed by a fold is removed)
    removed = set()
    rewire_map = {}  # removed node -> surviving producer (for outputs)
    for n in list(nodes):
        if n.name in removed:
            continue
        if n.op == "pad":
            consumers = [m for m in nodes if n.name in m.args
                         and m.name not in removed]
            if len(consumers) == 1 and consumers[0].op in (
                    "conv2d", "dw_conv2d"):
                conv = consumers[0]
                conv.kwargs["pad"] = tuple(n.kwargs["pad"])
                conv.kwargs["pad_mode"] = n.kwargs.get("mode", "zero")
                # rewire: the conv now consumes the pad's input
                conv.args = [a if a != n.name else n.args[0]
                             for a in conv.args]
                removed.add(n.name)
                rewire_map[n.name] = conv.name
                report.append(f"fold pad {n.name} (mode "
                              f"{n.kwargs.get('mode')} "
                              f"pad={n.kwargs['pad']}) into {conv.name}")
        if n.op == "batch_norm":
            # Fold BN into the PRECEDING conv (the conv that produces
            # the BN's input): BN(conv(x)) = conv'(x) with per-output-
            # channel weight scaling + bias adjustment (_fold_bn).
            # (Fixed 2026-11-20: the old code folded into a FOLLOWING
            # conv, which is wrong -- _fold_bn scales per OUTPUT
            # channel, so it only applies to the conv whose output
            # the BN normalizes. The old form never fired for the
            # standard conv->BN->relu pattern, so BN was silently
            # left unfolded.)
            src = by_name.get(n.args[0]) if n.args else None
            if src is not None and src.op in ("conv2d", "dw_conv2d",
                                              "linear"):
                _fold_bn(src, n)
                _rewire(nodes, n.name, src.name)
                removed.add(n.name)
                rewire_map[n.name] = src.name
                report.append(f"fold batch_norm {n.name} into {src.name}")

    nodes = [n for n in nodes if n.name not in removed]
    by_name = {n.name: n for n in nodes}

    # ---- pass 3: fuse relu/leaky into conv; rewrite complex acts ---
    removed = set()
    for n in list(nodes):
        if n.name in removed:
            continue
        if n.op == "relu":
            src = by_name.get(n.args[0]) if n.args else None
            if src is not None and src.op in ("conv2d", "dw_conv2d",
                                              "linear"):
                src.kwargs["fused_act"] = "relu"
                _rewire(nodes, n.name, src.name)
                removed.add(n.name)
                rewire_map[n.name] = src.name
                report.append(f"fuse relu {n.name} into {src.name} "
                              f"(conv output stage)")
        elif n.op == "leaky_relu":
            src = by_name.get(n.args[0]) if n.args else None
            if src is not None and src.op in ("conv2d", "dw_conv2d",
                                              "linear"):
                src.kwargs["fused_act"] = "leaky"
                src.kwargs["act_slope"] = n.kwargs.get(
                    "negative_slope", 0.01)
                _rewire(nodes, n.name, src.name)
                removed.add(n.name)
                rewire_map[n.name] = src.name
                report.append(f"fuse leaky_relu {n.name} into {src.name}")
        elif n.op in COMPLEX_ACTS:
            orig = n.op
            n.op = "act"
            n.kwargs["func"] = orig
            report.append(f"complex act {n.name} -> separate LUT act "
                          f"module (func={orig}, mode=mlut)")
    nodes = [n for n in nodes if n.name not in removed]
    by_name = {n.name: n for n in nodes}

    # ---- pass 4: rename elementwise two-tensor ops ------------------
    for n in nodes:
        if n.op in ("add", "sub") and len(n.args) == 2:
            n.kwargs["mode"] = n.op
            n.op = "residual"
            report.append(f"elementwise {n.name} -> residual "
                          f"(mode={n.kwargs['mode']})")
        elif n.op == "mul" and len(n.args) == 2:
            n.op = "simplegate"
            report.append(f"elementwise mul {n.name} -> simplegate")

    # ---- pass 5: fusion groups --------------------------------------
    groups = _group(nodes, tile_buffer_budget, report)

    g = Graph(graph.name + "_fused")
    g.inputs = list(graph.inputs)
    for n in nodes:
        g.add(n)
    g.outputs = [rewire_map.get(o, o) for o in graph.outputs]
    return g, groups, report


def _fold_bn(conv, bn):
    """Fold a BatchNorm node into a conv node's weights/bias."""
    gamma = bn.params.get("weight")
    beta = bn.params.get("bias")
    mean = bn.params.get("running_mean")
    var = bn.params.get("running_var")
    eps = bn.kwargs.get("eps", 1e-5)
    if gamma is None or mean is None or var is None:
        raise RuntimeError(f"fold_bn: batch_norm {bn.name} is missing "
                           f"params (weight/running_mean/running_var)")
    W = conv.params["weight"]
    b = conv.params.get("bias", np.zeros(W.shape[3], dtype=np.float32))
    scale = gamma / np.sqrt(var + eps)
    # W: (KH, KW, Cin, Cout); scale per output channel.
    W2 = W * scale.reshape(1, 1, 1, -1)
    b2 = (b - mean) * scale + (beta if beta is not None else 0.0)
    conv.params["weight"] = W2.astype(np.float32)
    conv.params["bias"] = b2.astype(np.float32)


def _rewire(nodes, old_name, new_name):
    """Replace all uses of old_name with new_name."""
    for m in nodes:
        m.args = [new_name if a == old_name else a for a in m.args]


def _group(nodes, budget, report):
    """Group consecutive nodes into on-chip fusion groups.

    Cut at: residual / simplegate (two streams), upsample / concat /
    layer_norm (resolution change or full-frame module), or when the
    group's largest tile intermediate would exceed the tile buffer
    budget. Pool stays in the same group as its producer (pool fusion).
    """
    CUT_OPS = ("residual", "simplegate", "upsample", "concat",
               "layer_norm")
    groups = []
    cur = []
    cur_max_bytes = 0
    for n in nodes:
        if n.op == "input":
            cur.append(n.name)
            continue
        if n.op in CUT_OPS:
            if cur:
                groups.append(cur)
            groups.append([n.name])
            cur = []
            cur_max_bytes = 0
            continue
        # Estimate this node's tile intermediate size (bytes) from its
        # output shape, if known (kwargs carry H/W/C_out when the
        # compiler knows them; otherwise use the producer's).
        est = _tile_bytes(n)
        if cur and cur_max_bytes + est > budget:
            groups.append(cur)
            cur = [n.name]
            cur_max_bytes = est
            report.append(f"cut fusion group before {n.name} "
                          f"(tile buffer {cur_max_bytes + est} > "
                          f"{budget} B)")
        else:
            cur.append(n.name)
            cur_max_bytes = max(cur_max_bytes, est)
    if cur:
        groups.append(cur)
    return groups


def _tile_bytes(node):
    """Rough tile intermediate size (bytes) for one node's output.
    Uses kwargs H/W/C_out when present; defaults to a 32x32 tile."""
    h = node.kwargs.get("H_out", node.kwargs.get("H", 32))
    w = node.kwargs.get("W_out", node.kwargs.get("W", 32))
    c = node.kwargs.get("C_out", node.kwargs.get("C", 1))
    try:
        return int(h) * int(w) * int(c)
    except (TypeError, ValueError):
        return 32 * 32
