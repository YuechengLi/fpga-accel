def _dna_conv(d, q, idx):
    """(Wf, bf, K, stride, pad) for registered conv L{idx}. The
    .npz's L{i}_W is already the BN-folded float weight (and for
    L0 the ImageNet-norm-folded weight), so the accelerator input
    is plain uint8."""
    Wf = d[f"L{idx}_W"].astype(np.float64)
    bf = d[f"L{idx}_b"].astype(np.float64)
    K = int(q[f"L{idx}"]["kernel"][0])
    s = int(q[f"L{idx}"]["stride"][0])
    return Wf, bf, K, s, K // 2


def _norm_bn_fold(d_float, idx, mean, std):
    """ImageNet-norm fold + BN fold for a conv that takes the RAW
    image as its input. The registered .npz folds the norm into
    L0 only, but the first block's shortcut (L2) also reads the
    raw image -- the BN-only folded weight in the .npz assumes a
    normalized input, so it is wrong here. Recompute the fold
    from the raw float weights: norm first, then BN.
    mean/std: ImageNet per-channel arrays."""
    W = d_float[f"L{idx}_W"].astype(np.float64)
    b = d_float[f"L{idx}_b"].astype(np.float64)
    Wn = W / std[None, None, :, None]
    bn0 = b - np.einsum("hwci,c->i", W, mean / std)
    eps = float(d_float[f"L{idx}_bn_eps"][0])
    s = (d_float[f"L{idx}_bn_w"].astype(np.float64)
         / np.sqrt(d_float[f"L{idx}_bn_var"].astype(np.float64) + eps))
    Wf = Wn * s[None, None, None, :]
    bf = (d_float[f"L{idx}_bn_b"].astype(np.float64)
          + (bn0 - d_float[f"L{idx}_bn_mean"].astype(np.float64)) * s)
    return Wf, bf


def build_dnanet_graph():
    """Hand-built DNANet (Res_CBAM_block, nested U-Net, deep
    supervision). Outputs: the 4 deep-supervision logits
    (final1..4); the sigmoid + threshold for the mask is CPU
    (the driver). The ChannelAttention fc1/fc2 modules are shared
    between the avg and max branches in torch, so the graph
    carries TWO nodes per module (same weights) -- one per branch.
    The up_4/up_8/up_16 bilinear upsamples are chained scale-2
    upsamples (the RTL is scale-2 only)."""
    d = np.load(os.path.join(DNA_DIR, "dnanet.npz"))
    q = json.load(open(os.path.join(DNA_DIR, "dnanet_quant.json")))
    d_float = np.load(os.path.join(DNA_DIR, "dnanet_float.npz"))
    IMAGENET_MEAN = np.array([0.485, 0.456, 0.406])
    IMAGENET_STD = np.array([0.229, 0.224, 0.225])
    paths = list(d["paths"])
    assert len(paths) == 154
    idx_of = {p: i for i, p in enumerate(paths)}

    L = []
    L.append({"op": "input", "name": "input"})

    def _cat(name, args):
        L.append(_node("concat", name, args))
        return name

    def _down(name, src):
        L.append(_node("downsample", name, [src]))
        return name

    def conv(name, idx, src, norm_fold=False):
        """norm_fold=True: fold the ImageNet norm into the weights
        as well (only for a conv that reads the RAW image -- the
        first block's shortcut; L0 already carries the fold in
        the .npz)."""
        if norm_fold:
            Wf, bf = _norm_bn_fold(d_float, idx, IMAGENET_MEAN,
                                   IMAGENET_STD)
            K = int(q[f"L{idx}"]["kernel"][0])
            s = int(q[f"L{idx}"]["stride"][0])
            L.append(_conv(name, src, Wf, bf, K, s, K // 2))
            return name
        Wf, bf, K, s, pad = _dna_conv(d, q, idx)
        L.append(_conv(name, src, Wf, bf, K, s, pad))
        return name

    def res_cbam(prefix, src):
        """One Res_CBAM_block. Returns the block output node name
        (the final ReLU). The shortcut exists iff the path is in
        the registered map (in_ch != out_ch); all strides are 1."""
        # conv1 -> bn1 (folded) -> relu (fused by the fusion pass)
        c1 = conv(prefix + ".conv1", idx_of[prefix + ".conv1"], src)
        L.append(_act(prefix + ".conv1_relu", c1, "relu"))
        # conv2 -> bn2 (folded); NO relu after bn2 -- the output
        # feeds the attention directly (it is signed).
        c2 = conv(prefix + ".conv2", idx_of[prefix + ".conv2"],
                  prefix + ".conv1_relu")
        # ChannelAttention: GAP + GMP, then fc1 -> relu -> fc2 per
        # branch (shared modules, duplicated nodes), add, sigmoid.
        L.append(_node("gap", prefix + ".ca_avg", [c2]))
        L.append(_node("gmax", prefix + ".ca_max", [c2]))
        ca_outs = []
        for branch, pool in (("avg", prefix + ".ca_avg"),
                             ("max", prefix + ".ca_max")):
            f1 = conv(prefix + f".ca.fc1_{branch}",
                      idx_of[prefix + ".ca.fc1"], pool)
            L.append(_act(prefix + f".ca.fc1_{branch}_relu", f1, "relu"))
            f2 = conv(prefix + f".ca.fc2_{branch}",
                      idx_of[prefix + ".ca.fc2"],
                      prefix + f".ca.fc1_{branch}_relu")
            ca_outs.append(f2)
        L.append(_node("add", prefix + ".ca_add", ca_outs))
        L.append(_act(prefix + ".ca_sig", prefix + ".ca_add", "sigmoid"))
        L.append(_node("mul", prefix + ".ca_mul",
                       [prefix + ".ca_sig", c2]))
        # SpatialAttention: channel mean + channel max -> cat (2ch)
        # -> 7x7 conv -> sigmoid -> multiply.
        L.append(_node("cmean", prefix + ".sa_mean",
                       [prefix + ".ca_mul"]))
        L.append(_node("cmax", prefix + ".sa_max",
                       [prefix + ".ca_mul"]))
        L.append(_node("concat", prefix + ".sa_cat",
                       [prefix + ".sa_mean", prefix + ".sa_max"]))
        s1 = conv(prefix + ".sa.conv1", idx_of[prefix + ".sa.conv1"],
                  prefix + ".sa_cat")
        L.append(_act(prefix + ".sa_sig", s1, "sigmoid"))
        L.append(_node("mul", prefix + ".sa_mul",
                       [prefix + ".sa_sig", prefix + ".ca_mul"]))
        # Residual add (shortcut 1x1 conv if it exists, else the
        # block input) then the final ReLU.
        if prefix + ".shortcut.0" in idx_of:
            # The first block's shortcut reads the RAW image, so
            # it needs the norm fold too (L0 alone is not enough).
            nf = (prefix == "conv0_0.0")
            sc = conv(prefix + ".shortcut.0",
                      idx_of[prefix + ".shortcut.0"], src,
                      norm_fold=nf)
            res_in = sc
        else:
            res_in = src
        L.append(_node("add", prefix + ".add",
                       [prefix + ".sa_mul", res_in]))
        L.append(_act(prefix + ".relu", prefix + ".add", "relu"))
        return prefix + ".relu"

    def make_layer(name, n_blocks, src):
        """A _make_layer Sequential of Res_CBAM_blocks."""
        x = src
        for b in range(n_blocks):
            x = res_cbam(f"{name}.{b}", x)
        return x

    def up_chain(name, src, n):
        """n chained scale-2 bilinear upsamples (the RTL formula)."""
        x = src
        for i in range(n):
            nm = f"{name}_{i}"
            L.append(_node("upsample", nm, [x],
                           {"mode": "bilinear_rtl", "scale": 2}))
            x = nm
        return x

    # Encoder + nested decoder (model_DNANet.py forward()).
    x0_0 = make_layer("conv0_0", 1, "input")
    L.append(_node("max_pool2d", "pool_x0_0", [x0_0],
                   {"K": (2, 2), "stride": (2, 2)}))
    x1_0 = make_layer("conv1_0", 2, "pool_x0_0")
    x0_1 = make_layer("conv0_1", 1,
                      _cat("cat_x0_1", [x0_0, up_chain("up_x1_0", x1_0, 1)]))
    L.append(_node("max_pool2d", "pool_x1_0", [x1_0],
                   {"K": (2, 2), "stride": (2, 2)}))
    x2_0 = make_layer("conv2_0", 2, "pool_x1_0")
    x1_1 = make_layer("conv1_1", 2,
                      _cat("cat_x1_1", [x1_0, up_chain("up_x2_0", x2_0, 1),
                                        _down("down_x0_1", x0_1)]))
    x0_2 = make_layer("conv0_2", 1,
                      _cat("cat_x0_2", [x0_0, x0_1,
                                        up_chain("up_x1_1", x1_1, 1)]))
    L.append(_node("max_pool2d", "pool_x2_0", [x2_0],
                   {"K": (2, 2), "stride": (2, 2)}))
    x3_0 = make_layer("conv3_0", 2, "pool_x2_0")
    x2_1 = make_layer("conv2_1", 2,
                      _cat("cat_x2_1", [x2_0, up_chain("up_x3_0", x3_0, 1),
                                        _down("down_x1_1", x1_1)]))
    x1_2 = make_layer("conv1_2", 2,
                      _cat("cat_x1_2", [x1_0, x1_1,
                                        up_chain("up_x2_1", x2_1, 1),
                                        _down("down_x0_2", x0_2)]))
    x0_3 = make_layer("conv0_3", 1,
                      _cat("cat_x0_3", [x0_0, x0_1, x0_2,
                                        up_chain("up_x1_2", x1_2, 1)]))
    L.append(_node("max_pool2d", "pool_x3_0", [x3_0],
                   {"K": (2, 2), "stride": (2, 2)}))
    x4_0 = make_layer("conv4_0", 2, "pool_x3_0")
    x3_1 = make_layer("conv3_1", 2,
                      _cat("cat_x3_1", [x3_0, up_chain("up_x4_0", x4_0, 1),
                                        _down("down_x2_1", x2_1)]))
    x2_2 = make_layer("conv2_2", 2,
                      _cat("cat_x2_2", [x2_0, x2_1,
                                        up_chain("up_x3_1", x3_1, 1),
                                        _down("down_x1_2", x1_2)]))
    x1_3 = make_layer("conv1_3", 2,
                      _cat("cat_x1_3", [x1_0, x1_1, x1_2,
                                        up_chain("up_x2_2", x2_2, 1),
                                        _down("down_x0_3", x0_3)]))
    x0_4 = make_layer("conv0_4", 1,
                      _cat("cat_x0_4", [x0_0, x0_1, x0_2, x0_3,
                                        up_chain("up_x1_3", x1_3, 1)]))
    # Final aggregation: 1x1 adapters + chained upsamples -> cat.
    a4 = conv("conv0_4_1x1", idx_of["conv0_4_1x1"], x4_0)
    a3 = conv("conv0_3_1x1", idx_of["conv0_3_1x1"], x3_1)
    a2 = conv("conv0_2_1x1", idx_of["conv0_2_1x1"], x2_2)
    a1 = conv("conv0_1_1x1", idx_of["conv0_1_1x1"], x1_3)
    fin = make_layer("conv0_4_final", 1,
                     _cat("cat_final",
                          [up_chain("up16_a4", a4, 4),
                           up_chain("up8_a3", a3, 3),
                           up_chain("up4_a2", a2, 2),
                           up_chain("up_a1", a1, 1), x0_4]))
    # Deep supervision (1x1 convs, signed logits, no activation).
    f1 = conv("final1", idx_of["final1"], x0_1)
    f2 = conv("final2", idx_of["final2"], x0_2)
    f3 = conv("final3", idx_of["final3"], x0_3)
    f4 = conv("final4", idx_of["final4"], fin)
    g = build_graph("dnanet", L)
    g.outputs = [f1, f2, f3, f4]
    return g


