def quantize_override(graph, float_input, registered=None):
    """Attach W_q/b_q/shift/r_in/r_out/signed_out to every node,
    with ranges measured on the e2e (blurred) float input via
    float_forward. ``registered`` is the model's quant.json (for
    the cross-check report only). Returns
    (report, r_out_of, signed_of).

    Rules (see the module docstring):
      conv: r_in = producer's r_out; r_out from the conv's OWN
        float output (pre-act for a separate-act conv, post-ReLU
        for a fused one); signed iff the output has a negative
        tail; W_q/b_q/shift from quantize_layer on the float
        weights (the registered W_q is the cross-check, not the
        source -- the e2e input differs from the calibration
        image, and the pre-act / signed ranges differ from the
        registered post-act / unsigned ones).
      act(sigmoid): r_in = producer's r_out, r_out = 2 (the
        halved-sigmoid trick; every sigmoid in 7d feeds a
        simplegate). act(silu): r_out = the measured post-SiLU
        range (the decomposition pass reads it).
      simplegate: r_out / signed_out from the float multiply
        output; the shift is set by configure_simplegates.
      residual: r_in = r_out = the coarsest input scale (no
        input clips on the rescale; only LSB loss).
      concat / upsample / pool / gap / gmax / cmean / cmax /
      downsample / relu: scale-preserving (r_out = the
        producer's r_out; a concat's r_out is the max of its
        inputs' -- the per-group scales are tracked by
        fixed_forward, not by a single r_out).
    """
    vals, _ = float_forward(graph, float_input)
    r_out_of = {}
    signed_of = {}
    report = []
    reg = registered or {}
    for n in graph.nodes:
        if n.op == "input":
            r_out_of[n.name] = 0
            signed_of[n.name] = False
            continue
        if n.op in ("conv2d", "dw_conv2d", "linear"):
            src = n.args[0]
            r_in = int(r_out_of.get(src, 0))
            Wf = n.params["weight"]
            bf = n.params.get("bias", np.zeros(Wf.shape[3]))
            out = vals[n.name]
            signed = bool(out.min() < 0)
            mx = float(np.abs(out).max())
            if signed:
                r_out = int(range_exp(2.0 * mx))
            else:
                r_out = int(range_exp(float(out.max())))
            W_q, b_q, shift, _scale = quantize_layer(
                Wf, bf, r_in=r_in, r_out=r_out)
            if not (0 <= shift <= 15):
                raise RuntimeError(
                    f"quantize_override: {n.name} shift={shift} out "
                    f"of [0, 15] (r_in={r_in} r_out={r_out} "
                    f"e={shift - r_out + r_in}) -- the e2e input "
                    f"range differs too much from the calibration; "
                    f"the capture cannot represent this layer")
            n.kwargs["shift"] = int(shift)
            n.kwargs["r_in"] = r_in
            n.kwargs["r_out"] = r_out
            n.kwargs["signed_out"] = bool(signed)
            n.kwargs["weight_exp_e"] = int(shift - r_out + r_in)
            n.params["W_q"] = W_q
            n.params["b_q"] = b_q
            r_out_of[n.name] = r_out
            signed_of[n.name] = bool(signed)
            # Cross-check vs the registered quant (same node name
            # for YOLO C{i}; for DNANet the node name is the path,
            # so fall back to the registered entry whose "path"
            # field matches).
            key = n.name if n.name in reg else None
            if key is None and reg:
                for k, v in reg.items():
                    if isinstance(v, dict) and v.get("path") == n.name:
                        key = k
                        break
            if key is not None:
                rq = reg[key]
                dshift = int(shift) - int(rq["shift"])
                report.append(
                    f"{n.name}: shift={shift} r {r_in}->{r_out} "
                    f"signed={int(signed)} "
                    f"(registered shift={rq['shift']} "
                    f"r {rq['r_in']}->{rq['r_out']} "
                    f"dshift={dshift:+d})")
            else:
                report.append(
                    f"{n.name}: shift={shift} r {r_in}->{r_out} "
                    f"signed={int(signed)} (no registered entry)")
            continue
        if n.op == "act":
            src = n.args[0]
            n.kwargs["r_in"] = int(r_out_of.get(src, 0))
            if n.kwargs.get("func") == "sigmoid":
                n.kwargs["r_out"] = 2
            else:
                out = vals[n.name]
                n.kwargs["r_out"] = int(range_exp(float(out.max())))
            n.kwargs["signed_out"] = False
            r_out_of[n.name] = int(n.kwargs["r_out"])
            signed_of[n.name] = False
            continue
        if n.op == "simplegate":
            out = vals[n.name]
            signed = bool(out.min() < 0)
            mx = float(np.abs(out).max())
            r_out = int(range_exp(2.0 * mx)) if signed \
                else int(range_exp(float(out.max())))
            n.kwargs["r_out"] = r_out
            n.kwargs["signed_out"] = bool(signed)
            r_out_of[n.name] = r_out
            signed_of[n.name] = bool(signed)
            continue
        if n.op == "residual":
            r_a = int(r_out_of.get(n.args[0], 0))
            r_b = int(r_out_of.get(n.args[1], 0))
            r_in = max(r_a, r_b)
            n.kwargs["r_in"] = r_in
            n.kwargs["r_out"] = r_in
            n.kwargs["signed_out"] = False
            r_out_of[n.name] = r_in
            signed_of[n.name] = False
            continue
        if n.op == "relu":
            src = n.args[0]
            r = int(r_out_of.get(src, 0))
            n.kwargs["r_in"] = r
            n.kwargs["r_out"] = r
            n.kwargs["signed_out"] = False
            r_out_of[n.name] = r
            signed_of[n.name] = False
            continue
        if n.op in ("upsample", "max_pool2d", "avg_pool2d", "gap",
                    "gmax", "cmean", "cmax", "downsample", "bypass"):
            src = n.args[0]
            r = int(r_out_of.get(src, 0))
            n.kwargs["r_in"] = r
            n.kwargs["r_out"] = r
            n.kwargs["signed_out"] = bool(signed_of.get(src, False))
            r_out_of[n.name] = r
            signed_of[n.name] = bool(signed_of.get(src, False))
            continue
        if n.op == "concat":
            r = max(int(r_out_of.get(a, 0)) for a in n.args)
            n.kwargs["r_out"] = r
            r_out_of[n.name] = r
            signed_of[n.name] = any(signed_of.get(a, False)
                                    for a in n.args)
            continue
        raise RuntimeError(f"quantize_override: unsupported op "
                           f"{n.op} (node {n.name})")
    return report, r_out_of, signed_of


def configure_simplegates(graph, r_out_of):
    """Set every simplegate's shift (and sign_in/sign_out) by the
    halved-sigmoid formula. One arg is an act(sigmoid) node with
    r_out=2 (the halved map, in [0,64]); the other is the signed
    tensor with r_out R_B. shift = r_out_sg - R_B + 6 (the
    255-vs-256 scale difference is the documented quantization
    error). Idempotent: the SiLU decomposition pass already sets
    the same shift; this recomputes it and asserts agreement.
    Returns the report."""
    by_name = {n.name: n for n in graph.nodes}
    report = []
    for n in graph.nodes:
        if n.op != "simplegate":
            continue
        sig = None
        other = None
        for a in n.args:
            m = by_name[a]
            if m.op == "act" and m.kwargs.get("func") == "sigmoid":
                sig = m
            else:
                other = m
        if sig is None or other is None:
            raise RuntimeError(
                f"configure_simplegates: {n.name} has no sigmoid "
                f"act arg (args={n.args}) -- the halved-sigmoid "
                f"trick needs one")
        assert int(sig.kwargs.get("r_out", -1)) == 2, \
            f"{sig.name} r_out != 2 (halved sigmoid)"
        R_B = int(r_out_of.get(other.name,
                               other.kwargs.get("r_out", 0)))
        Ro = int(n.kwargs["r_out"])
        shift = Ro - R_B + 6
        if not (0 <= shift <= 15):
            raise RuntimeError(
                f"configure_simplegates: {n.name} shift={shift} "
                f"out of [0, 15] (Ro={Ro}, R_B={R_B})")
        if "shift" in n.kwargs:
            assert int(n.kwargs["shift"]) == shift, \
                (f"{n.name}: decomposition shift "
                 f"{n.kwargs['shift']} != recomputed {shift}")
        n.kwargs["shift"] = shift
        n.kwargs["sign_in"] = True
        n.kwargs["sign_out"] = bool(n.kwargs.get("signed_out", False))
        n.kwargs["r_in"] = R_B
        report.append(f"{n.name}: simplegate shift={shift} "
                      f"(Ro={Ro} R_B={R_B} map={sig.name})")
    return report


def gen_act_tables(graph, err_budget=0.03):
    """Generate the MLUT/PWL tables for every act node (sigmoid
    only in 7d -- the SiLU is decomposed). Same code as
    compile_model's actapprox loop. Returns (tables, report)."""
    tables = {}
    report = []
    for n in graph.nodes:
        if n.op != "act":
            continue
        func = n.kwargs["func"]
        choice = choose_act_impl(func, err_budget)
        if choice["impl"] == "pwl":
            y0, ds, mx, _ok = pwl_table(func, err_budget)
            cw = []
            for s in range(32):
                cw.append((0x100 + s * 2, y0[s] & 0xFFFF))
                cw.append((0x100 + s * 2 + 1, ds[s] & 0xFFFF))
            tables[n.name] = {"impl": "pwl", "y0": y0, "dslope": ds,
                              "max_err": mx, "config_writes": cw}
            report.append(f"{n.name} ({func}): PWL 32-seg "
                          f"max_err={mx:.4f}")
        else:
            h1, h2, nb, base, sel, fine, mx, total = mlut_search(
                func, err_budget)
            cw = mlut_config_writes(func, h1, h2, base, sel, fine)
            tables[n.name] = {"impl": "mlut", "H1": h1, "H2": h2,
                              "nbands": nb, "base": base, "sel": sel,
                              "fine": fine, "max_err": mx,
                              "entries": total, "config_writes": cw}
            report.append(f"{n.name} ({func}): MLUT H1={h1} H2={h2} "
                          f"bands={nb} max_err={mx:.4f}")
    return tables, report


def emit_7d_program(graph, act_tables, input_shape):
    """Build the program dict fixed_forward executes. Ops carry
    the kwargs the driver needs too (signed_in for the PE,
    shift for the simplegate, mode/scale for the upsample)."""
    ops = []
    weights = {}
    for n in graph.nodes:
        if n.op == "input":
            ops.append({"name": n.name, "op": "input", "args": [],
                        "shape": list(input_shape)})
            continue
        op = {"name": n.name, "op": n.op, "args": list(n.args)}
        op.update(n.kwargs)
        if n.op in ("conv2d", "dw_conv2d", "linear"):
            weights[n.name] = {"W_q": n.params["W_q"],
                               "b_q": n.params["b_q"]}
        ops.append(op)
    return {"ops": ops, "weights": weights,
            "act_tables": act_tables, "outputs": list(graph.outputs),
            "_weights_arrays": weights,
            "_act_tables_full": act_tables}


def capture(model, float_input, input_shape, err_budget=0.03):
    """Full capture for one model. ``float_input`` is the e2e
    (blurred) input as float (H, W, C) in [0, 1]. Returns
    (program, report_dict)."""
    if model == "yolo":
        graph = build_yolo_graph()
        reg = json.load(open(os.path.join(
            YOLO_DIR, "yolov8n_quant.json")))
    elif model == "dnanet":
        graph = build_dnanet_graph()
        reg = json.load(open(os.path.join(
            DNA_DIR, "dnanet_quant.json")))
    else:
        raise ValueError(model)
    report = {"model": model, "passes": {}}
    fused, _groups, freport = fuse(graph)
    report["passes"]["fusion"] = freport
    report["n_nodes_fused"] = len(fused.nodes)
    qreport, r_out_of, _signed_of = quantize_override(
        fused, float_input, registered=reg)
    report["passes"]["quantize"] = qreport
    decomposed, dreport = decompose_silu(fused)
    report["passes"]["silu_decompose"] = dreport
    # The decomposition renames nothing the override recorded
    # (the simplegate reuses the act node's name), but the new
    # sigmoid nodes need their r_out in r_out_of for the
    # simplegate configuration.
    for n in decomposed.nodes:
        if n.op == "act" and n.kwargs.get("func") == "sigmoid":
            r_out_of[n.name] = int(n.kwargs["r_out"])
    sreport = configure_simplegates(decomposed, r_out_of)
    report["passes"]["simplegate"] = sreport
    tables, areport = gen_act_tables(decomposed, err_budget)
    report["passes"]["actapprox"] = areport
    program = emit_7d_program(decomposed, tables, input_shape)
    # Consistency: the decomposed graph's float forward must match
    # the fused graph's (the decomposition is exact in float).
    vals_f, _ = float_forward(fused, float_input)
    vals_d, _ = float_forward(decomposed, float_input)
    worst = 0.0
    for o in decomposed.outputs:
        a = vals_f[o]
        b = vals_d[o]
        worst = max(worst, float(np.abs(a - b).max()))
    report["decompose_float_maxdiff"] = worst
    assert worst < 1e-9, \
        f"SiLU decomposition changed the float output by {worst}"
    # And fixed_forward must run on the program.
    per_layer, _out = fixed_forward(program,
                                    np.clip(np.round(
                                        float_input * 255.0),
                                        0, 255).astype(np.uint8))
    report["n_nodes_program"] = len(program["ops"])
    report["n_outputs"] = len(program["outputs"])
    report["fixed_forward_nodes"] = sorted(per_layer.keys())
    return program, report


