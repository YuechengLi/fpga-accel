# ---------------------------------------------------------------------------
# Node helpers (pre-fusion form).
# ---------------------------------------------------------------------------
def _conv(name, src, Wf, bf, K, stride=1, pad=0):
    """A conv2d node. Wf/bf are the BN-folded FLOAT weights
    (KH,KW,Cin,Cout) / (Cout,). pad is a symmetric int -> (t,b,l,r)."""
    return {"op": "conv2d", "name": name, "args": [src],
            "kwargs": {"K": int(K), "C_in": int(Wf.shape[2]),
                       "C_out": int(Wf.shape[3]),
                       "stride": (int(stride), int(stride)),
                       "pad": (int(pad), int(pad), int(pad), int(pad))},
            "params": {"weight": np.asarray(Wf, dtype=np.float64),
                       "bias": np.asarray(bf, dtype=np.float64)}}


def _split_conv(name_a, name_b, src, Wf, bf, K, stride=1, pad=0):
    """Split a conv's output channels in half (the C2f cv1 trick):
    two conv nodes, the first / last c output channels. A conv's
    output channels are independent, so this is exact. Returns the
    two node dicts."""
    c = int(Wf.shape[3]) // 2
    assert Wf.shape[3] == 2 * c, "split needs an even channel count"
    a = _conv(name_a, src, Wf[:, :, :, :c], bf[:c], K, stride, pad)
    b = _conv(name_b, src, Wf[:, :, :, c:], bf[c:], K, stride, pad)
    return a, b


def _act(name, src, func):
    return {"op": func, "name": name, "args": [src], "kwargs": {}}


def _node(op, name, args, kwargs=None):
    return {"op": op, "name": name, "args": list(args),
            "kwargs": dict(kwargs or {})}


# ---------------------------------------------------------------------------
# YOLOv8n.
# ---------------------------------------------------------------------------
# C-index -> (module path) is read from the npz's `paths` array; the
# topology below is the measured ultralytics module tree (see
# design.md): model.0/1 Conv, model.2/4/6/8 C2f (backbone),
# model.9 SPPF, model.10-21 neck, model.22 Detect.
def _yolo_conv(d, q, idx):
    """(Wf, bf, K, stride, pad) for registered conv C{idx}."""
    Wf = d[f"C{idx}_W"].astype(np.float64)
    bf = d[f"C{idx}_b"].astype(np.float64)
    K = int(q[f"C{idx}"]["kernel"][0])
    s = int(q[f"C{idx}"]["stride"][0])
    pad = K // 2
    return Wf, bf, K, s, pad


def build_yolo_graph():
    """Hand-built YOLOv8n backbone+neck+Detect-conv graph.
    Outputs: the 6 Detect-conv outputs (box/cls per scale).
    The Detect head's DFL+NMS stay on CPU (the driver)."""
    d = np.load(os.path.join(YOLO_DIR, "yolov8n.npz"))
    q = json.load(open(os.path.join(YOLO_DIR, "yolov8n_quant.json")))
    paths = list(d["paths"])
    assert len(paths) == 57
    idx_of = {p: i for i, p in enumerate(paths)}

    def C(path):
        return idx_of[path]

    L = []  # layer dicts for build_graph
    L.append({"op": "input", "name": "input"})

    def conv_silu(idx, src):
        """A registered conv C{idx} + its SiLU (separate node;
        fusion rewrites it to an act node, the decomposition pass
        then splits it into sigmoid + simplegate). The conv node
        is named C{idx}, the SiLU node C{idx}_silu."""
        Wf, bf, K, s, pad = _yolo_conv(d, q, idx)
        name = f"C{idx}"
        L.append(_conv(name, src, Wf, bf, K, s, pad))
        L.append(_act(name + "_silu", name, "silu"))
        return name + "_silu"

    def c2f(tag, cv1_idx, cv2_idx, bottleneck_idxs, src, shortcut):
        """A C2f module. bottleneck_idxs is a list of (cv1, cv2)
        index pairs. Returns the C2f output node name (the cv2
        SiLU). The cv1 split uses C{cv1}a / C{cv1}b."""
        Wf, bf, K, s, pad = _yolo_conv(d, q, cv1_idx)
        assert K == 1 and s == 1
        a, b = _split_conv(f"C{cv1_idx}a", f"C{cv1_idx}b", src,
                           Wf, bf, K, s, pad)
        L.append(a)
        L.append(b)
        L.append(_act(f"C{cv1_idx}a_silu", f"C{cv1_idx}a", "silu"))
        L.append(_act(f"C{cv1_idx}b_silu", f"C{cv1_idx}b", "silu"))
        parts = [f"C{cv1_idx}a_silu", f"C{cv1_idx}b_silu"]
        y1 = f"C{cv1_idx}b_silu"
        for j, (b1, b2) in enumerate(bottleneck_idxs):
            b1_out = conv_silu(b1, y1)
            b2_out = conv_silu(b2, b1_out)
            if shortcut:
                L.append(_node("add", f"{tag}_m{j}_add",
                               [y1, b2_out]))
                y1 = f"{tag}_m{j}_add"
            else:
                y1 = b2_out
            parts.append(y1)
        L.append(_node("concat", tag + "_cat", parts))
        return conv_silu(cv2_idx, tag + "_cat")

    # Backbone.
    x = conv_silu(C("model.0"), "input")
    x = conv_silu(C("model.1"), x)
    x = c2f("c2f2", C("model.2.cv1"), C("model.2.cv2"),
            [(C("model.2.m.0.cv1"), C("model.2.m.0.cv2"))], x, True)
    x = conv_silu(C("model.3"), x)
    x = c2f("c2f4", C("model.4.cv1"), C("model.4.cv2"),
            [(C("model.4.m.0.cv1"), C("model.4.m.0.cv2")),
             (C("model.4.m.1.cv1"), C("model.4.m.1.cv2"))], x, True)
    m4 = x
    x = conv_silu(C("model.5"), x)
    x = c2f("c2f6", C("model.6.cv1"), C("model.6.cv2"),
            [(C("model.6.m.0.cv1"), C("model.6.m.0.cv2")),
             (C("model.6.m.1.cv1"), C("model.6.m.1.cv2"))], x, True)
    m6 = x
    x = conv_silu(C("model.7"), x)
    x = c2f("c2f8", C("model.8.cv1"), C("model.8.cv2"),
            [(C("model.8.m.0.cv1"), C("model.8.m.0.cv2"))], x, True)
    # SPPF (model.9): cv1 -> silu -> 3x 5x5 maxpool (CPU) -> cat -> cv2.
    x = conv_silu(C("model.9.cv1"), x)
    L.append(_node("max_pool2d", "sppf_m1", [x],
                   {"K": (5, 5), "stride": (1, 1),
                    "pad": (2, 2, 2, 2)}))
    L.append(_node("max_pool2d", "sppf_m2", ["sppf_m1"],
                   {"K": (5, 5), "stride": (1, 1),
                    "pad": (2, 2, 2, 2)}))
    L.append(_node("max_pool2d", "sppf_m3", ["sppf_m2"],
                   {"K": (5, 5), "stride": (1, 1),
                    "pad": (2, 2, 2, 2)}))
    L.append(_node("concat", "sppf_cat",
                   [x, "sppf_m1", "sppf_m2", "sppf_m3"]))
    x = conv_silu(C("model.9.cv2"), "sppf_cat")
    m9 = x
    # Neck.
    L.append(_node("upsample", "up10", [m9],
                   {"mode": "nearest", "scale": 2}))
    L.append(_node("concat", "cat11", ["up10", m6]))
    x = c2f("c2f12", C("model.12.cv1"), C("model.12.cv2"),
            [(C("model.12.m.0.cv1"), C("model.12.m.0.cv2"))],
            "cat11", False)
    m12 = x
    L.append(_node("upsample", "up13", [m12],
                   {"mode": "nearest", "scale": 2}))
    L.append(_node("concat", "cat14", ["up13", m4]))
    x = c2f("c2f15", C("model.15.cv1"), C("model.15.cv2"),
            [(C("model.15.m.0.cv1"), C("model.15.m.0.cv2"))],
            "cat14", False)
    p3 = x
    x = conv_silu(C("model.16"), p3)
    L.append(_node("concat", "cat17", [x, m12]))
    x = c2f("c2f18", C("model.18.cv1"), C("model.18.cv2"),
            [(C("model.18.m.0.cv1"), C("model.18.m.0.cv2"))],
            "cat17", False)
    p4 = x
    x = conv_silu(C("model.19"), p4)
    L.append(_node("concat", "cat20", [x, m9]))
    x = c2f("c2f21", C("model.21.cv1"), C("model.21.cv2"),
            [(C("model.21.m.0.cv1"), C("model.21.m.0.cv2"))],
            "cat20", False)
    p5 = x
    # Detect head convs (cv2 = box branch, cv3 = cls branch).
    # Each branch is THREE convs: two Conv (3x3, SiLU) + a plain
    # 1x1 Conv2d with NO BN and NO activation. The plain 1x1 is
    # the Detect head's actual output (it is NOT a UConv, so the
    # registration's 57-conv count missed it -- the model has 63
    # conv layers). Its weights live in detect_out.npz.
    det = np.load(os.path.join(YOLO_DIR, "detect_out.npz"))
    box, cls = [], []
    for j, (p_in, cv2a, cv2b, cv3a, cv3b) in enumerate([
            (p3, C("model.22.cv2.0.0"), C("model.22.cv2.0.1"),
             C("model.22.cv3.0.0"), C("model.22.cv3.0.1")),
            (p4, C("model.22.cv2.1.0"), C("model.22.cv2.1.1"),
             C("model.22.cv3.1.0"), C("model.22.cv3.1.1")),
            (p5, C("model.22.cv2.2.0"), C("model.22.cv2.2.1"),
             C("model.22.cv3.2.0"), C("model.22.cv3.2.1"))]):
        b = conv_silu(cv2a, p_in)
        b = conv_silu(cv2b, b)
        # Plain 1x1 output conv (no BN, no act).
        bn = f"det_box{j}"
        L.append(_conv(bn, b, det[f"cv2.{j}.2_W"].astype(np.float64),
                       det[f"cv2.{j}.2_b"].astype(np.float64),
                       1, 1, 0))
        box.append(bn)
        c = conv_silu(cv3a, p_in)
        c = conv_silu(cv3b, c)
        cn = f"det_cls{j}"
        L.append(_conv(cn, c, det[f"cv3.{j}.2_W"].astype(np.float64),
                       det[f"cv3.{j}.2_b"].astype(np.float64),
                       1, 1, 0))
        cls.append(cn)
    g = build_graph("yolov8n", L)
    g.outputs = [box[0], cls[0], box[1], cls[1], box[2], cls[2]]
    return g


