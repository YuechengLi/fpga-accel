def save_program(model, program, report, outdir):
    """Save the program (npz: the W_q/b_q arrays + the op list as
    JSON) and the capture report."""
    os.makedirs(outdir, exist_ok=True)
    npz = {}
    for name, w in program["weights"].items():
        npz[f"{name}__W_q"] = w["W_q"]
        npz[f"{name}__b_q"] = w["b_q"]
    np.savez(os.path.join(outdir, f"program_{model}.npz"), **npz)
    ops_json = []
    for op in program["ops"]:
        o = dict(op)
        # numpy types are not JSON-safe; convert the small ints.
        for k, v in list(o.items()):
            if isinstance(v, (np.integer,)):
                o[k] = int(v)
            elif isinstance(v, tuple):
                o[k] = list(v)
        ops_json.append(o)
    # The act tables carry numpy arrays (base/sel/fine/y0/dslope);
    # store them in the npz too and keep only the summary in JSON.
    for name, t in program["act_tables"].items():
        for k in ("base", "sel", "fine", "y0", "dslope"):
            if k in t:
                npz[f"act_{name}__{k}"] = np.asarray(t[k])
    np.savez(os.path.join(outdir, f"program_{model}.npz"), **npz)
    tables_json = {}
    for name, t in program["act_tables"].items():
        tj = {k: v for k, v in t.items()
              if k not in ("base", "sel", "fine", "y0", "dslope")}
        tj["config_writes"] = [[int(a), int(b)]
                               for a, b in t["config_writes"]]
        tables_json[name] = tj
    with open(os.path.join(outdir, f"program_{model}.json"), "w") as f:
        json.dump({"ops": ops_json, "act_tables": tables_json,
                   "outputs": program["outputs"]}, f, indent=2)
    with open(os.path.join(outdir, f"capture_{model}.json"), "w") as f:
        json.dump(report, f, indent=2, default=str)
    return (os.path.join(outdir, f"program_{model}.npz"),
            os.path.join(outdir, f"program_{model}.json"))


def load_program(model, outdir):
    """Rebuild the program dict (with the runtime arrays) from the
    saved files."""
    d = np.load(os.path.join(outdir, f"program_{model}.npz"))
    with open(os.path.join(outdir, f"program_{model}.json")) as f:
        j = json.load(f)
    weights = {}
    for key in d.files:
        if "__W_q" in key:
            name = key.split("__W_q")[0]
            weights[name] = {"W_q": d[key], "b_q": d[f"{name}__b_q"]}
    tables = {}
    for name, tj in j["act_tables"].items():
        t = dict(tj)
        t["config_writes"] = [(a, b) for a, b in tj["config_writes"]]
        for k in ("base", "sel", "fine", "y0", "dslope"):
            ak = f"act_{name}__{k}"
            if ak in d.files:
                t[k] = [int(v) for v in d[ak]]
        tables[name] = t
    ops = []
    for o in j["ops"]:
        oo = dict(o)
        for k in ("pad", "stride", "shape"):
            if k in oo and isinstance(oo[k], list):
                oo[k] = tuple(oo[k])
        ops.append(oo)
    prog = {"ops": ops, "weights": weights, "act_tables": tables,
            "outputs": j["outputs"],
            "_weights_arrays": weights, "_act_tables_full": tables}
    return prog


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="all",
                    choices=["yolo", "dnanet", "all"])
    ap.add_argument("--outdir", default="logs/stage7d")
    ap.add_argument("--yolo-size", type=int, default=128)
    ap.add_argument("--dnanet-size", type=int, default=64)
    args = ap.parse_args()
    outdir = os.path.join(REPO, args.outdir)
    os.makedirs(outdir, exist_ok=True)
    # The e2e float inputs. The 7d models take the RAW image (the
    # capture calibrates on it here and the driver feeds the same
    # raw image to the PE chain). There is NO frontend blur in the
    # 7d e2e: the frontend is the 7c enhancement models'
    # preprocessing, and YOLO/DNANet were trained on raw images
    # (a blur would only degrade the detection/segmentation).
    # This main() is for a standalone smoke check only.
    from PIL import Image
    want = ["yolo", "dnanet"] if args.model == "all" \
        else [args.model]
    for model in want:
        if model == "yolo":
            im = np.array(Image.open(os.path.join(
                YOLO_DIR, "bus.jpg")).convert("RGB"))
            im = np.array(Image.fromarray(im).resize(
                (args.yolo_size, args.yolo_size), Image.BILINEAR))
            fin = im.astype(np.float64) / 255.0
            shape = (args.yolo_size, args.yolo_size, 3)
        else:
            im = np.array(Image.open(os.path.join(
                DNA_DIR, "target1.png")).convert("RGB"))
            # 64x64 crop centred on the target (x[159,161],
            # y[235,237] in the 256 image).
            crop = im[192:256, 128:192, :]
            assert crop.shape == (64, 64, 3), crop.shape
            fin = crop.astype(np.float64) / 255.0
            shape = (64, 64, 3)
        prog, rep = capture(model, fin, shape)
        save_program(model, prog, rep, outdir)
        print(f"capture {model}: {rep['n_nodes_program']} program ops, "
              f"{len(rep['passes']['quantize'])} quantized convs, "
              f"decompose float maxdiff={rep['decompose_float_maxdiff']:.2e}")
    return 0


