#!/usr/bin/env python3
"""Stage 7d compiler graph capture: hand-built IR graphs for YOLOv8n
and DNANet, plus the quantize override and program emission.

Why hand-built (design.md): torch.export / FX capture fails for
both models (YOLO: the neck's multi-output routing does not export;
DNANet: aten.batch_norm has no IR lowering, and ir.py is outside
this stage's file boundary). So the graphs are built from the
registered topology + weights via ir.build_graph, in pre-fusion
form (conv -> relu/silu as separate nodes, weights already
BN-folded by the registration), then the existing passes run:
fuse -> quantize override (below) -> silu_decompose -> attention
configuration -> actapprox (sigmoid tables) -> program emission.

Quantize override (NOT quantize_graph): the registered
quantization (bb37ce7) is the verified artifact, but its r_out is
the POST-act range, while the compiler needs the conv's own
(pre-act) range for the act node, and its signedness is decided
by the conv's consumer, not by the registration's convention.
So the override re-quantizes each conv from the FLOAT weights
(the registered .npz's Wf/bf) with ranges measured on the e2e
input via float_forward, and records every deviation from the
registered quant.json in the capture report. The cases where the
override differs from the registration (and why):
  * SiLU/sigmoid-headed convs: the registered r_out is the
    post-act range; the override uses the pre-act (logit) range
    for the conv and sets the act node's r_in/r_out separately.
  * DNANet conv2 (Res_CBAM_block): the BN output is SIGNED
    (min_act down to -24) and feeds the attention multiply, but
    the registration stored signed_out=False and compared the
    fixed check after clipping BOTH sides to [0,255], hiding the
    negative-tail loss. The override sets signed_out=True with
    the symmetric range (r_out = range_exp(2*max|out|)).
  * DNANet fc2 / sa.conv1 (sigmoid-headed): the registered
    r_out=0 is the post-sigmoid range, but the conv outputs a
    LOGIT (up to +/-208) that would saturate a byte at that
    scale. The override uses the logit range for the conv.
  * DNANet final1-4: signed logits (the registration agrees).

The override's r_in for a conv is its producer's r_out (the
compiler's rule); for a branching consumer (a concat feeding a
conv, or a residual add of two differently-scaled tensors) the
driver and fixed_forward apply a per-channel-group rescale
(funcsim.rescale_input) from the producer's scale to the
consumer's r_in. The rescale is a byte shift, defined once in
funcsim and used by both, so they agree exactly.

The act tables are generated by the same actapprox/mlut code as
compile_model (choose_act_impl + mlut_search / pwl_table), for
the sigmoid act nodes only (the SiLU is decomposed, so no SiLU
table is ever generated).

Program emission: the program dict is built directly (not via
emit.emit_program, which is the iterative-program emitter and
does not carry the 7d nodes' r_in/r_out/rescale metadata). The
format is the one fixed_forward executes: ops (name/op/args +
kwargs), weights {name: {W_q, b_q}}, act_tables, outputs.

Usage:
  python3 sw/vision/capture_7d.py [--model yolo|dnanet|all]
      [--outdir logs/stage7d] [--yolo-size 128] [--dnanet-size 64]
Builds the graph, runs the passes, emits the program + the
capture report (logs/stage7d/capture_<model>.json) and the
program files (logs/stage7d/program_<model>.npz + .json).
The driver (run_e2e_7d.py) loads the program files.
"""
